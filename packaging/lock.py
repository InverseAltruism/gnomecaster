#!/usr/bin/env python3
"""Turns the exact pins in packaging/*.in into hash-locked requirements for the Windows build.

  python3 packaging/lock.py           write packaging/requirements-*.txt
  python3 packaging/lock.py --check   exit 1 if a .txt file differs from what would be written

The .in files are installed in stages (backend, build, app; see packaging/README.md) and
together form one set of pins. For every pin it asks PyPI for that release and refuses it when
  - the release is younger than 14 days (the install cooldown),
  - the package is pinned in more than one file, or
  - one of its dependencies for Windows, CPython 3.13, x64 is not pinned in any of the files
    with a version the dependency accepts.
Only the files pip can choose on the build machine are hashed: wheels for cp313/abi3 on
win_amd64, pure-Python wheels, and source archives. Needs the `packaging` library.
"""
from __future__ import annotations

import datetime
import json
import pathlib
import sys
import urllib.request

from packaging.markers import default_environment
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

HERE = pathlib.Path(__file__).resolve().parent
COOLDOWN = datetime.timedelta(days=14)
TARGET = {**default_environment(), "sys_platform": "win32", "platform_system": "Windows", "os_name": "nt",
          "platform_machine": "AMD64", "python_version": "3.13", "python_full_version": "3.13.16",
          "implementation_name": "cpython", "platform_python_implementation": "CPython"}
WHEEL_TAGS = ("-cp313-cp313-win_amd64.whl", "-abi3-win_amd64.whl", "-none-any.whl", "-none-win_amd64.whl")


def release(name: str, version: str) -> dict:
    with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{version}/json", timeout=30) as r:
        return json.load(r)


def read_pins(source: pathlib.Path) -> dict[str, tuple[str, str]]:
    pins = {}
    for line in source.read_text().splitlines():
        line = line.split("#")[0].strip()
        if line:
            req = Requirement(line)
            (version,) = [s.version for s in req.specifier if s.operator == "=="]
            pins[canonicalize_name(req.name)] = (req.name, version)
    return pins


def lock(source: pathlib.Path, everything: dict, now: datetime.datetime) -> tuple[str, list[str]]:
    problems = []
    out = [f"# Generated by packaging/lock.py from {source.name}; edit that file, not this one.", ""]
    for key, (name, version) in sorted(read_pins(source).items()):
        data = release(name, version)
        files = [f for f in data["urls"] if f["packagetype"] == "sdist" or f["filename"].endswith(WHEEL_TAGS)]
        if not files:
            problems.append(f"{name}=={version}: no file for Windows x64 / CPython 3.13")
            continue
        uploaded = max(datetime.datetime.fromisoformat(f["upload_time_iso_8601"].replace("Z", "+00:00")) for f in data["urls"])
        if now - uploaded < COOLDOWN:
            problems.append(f"{name}=={version}: released {uploaded:%Y-%m-%d}, inside the 14-day cooldown")
        for dep in data["info"].get("requires_dist") or []:
            r = Requirement(dep)
            if r.marker is not None and not r.marker.evaluate({**TARGET, "extra": ""}):
                continue
            pinned = everything.get(canonicalize_name(r.name))
            if pinned is None:
                problems.append(f"{name}=={version} needs {dep}, which no requirements-*.in pins")
            elif not r.specifier.contains(pinned[1], prereleases=True):
                problems.append(f"{name}=={version} needs {dep}, but {pinned[1]} is pinned")
        hashes = sorted({f["digests"]["sha256"] for f in files})
        out.append(f"{name}=={version} \\")
        out += [f"    --hash=sha256:{h}" + (" \\" if i < len(hashes) - 1 else "") for i, h in enumerate(hashes)]
    return "\n".join(out) + "\n", problems


def main() -> int:
    check = "--check" in sys.argv[1:]
    now = datetime.datetime.now(datetime.timezone.utc)
    sources = sorted(HERE.glob("requirements-*.in"))
    everything, failed = {}, False
    for source in sources:
        for key, pin in read_pins(source).items():
            if key in everything:
                print(f"PROBLEM: {pin[0]} is pinned in more than one requirements-*.in")
                failed = True
            everything[key] = pin
    for source in sources:
        text, problems = lock(source, everything, now)
        target = source.with_suffix(".txt")
        for p in problems:
            print("PROBLEM:", p)
        failed |= bool(problems)
        if check:
            if not target.exists() or target.read_text() != text:
                print(f"out of date: {target.name} (run packaging/lock.py)")
                failed = True
        elif not problems:
            target.write_text(text)
            print(f"wrote {target.name}")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
